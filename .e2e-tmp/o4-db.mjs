import { readFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
const env = readFileSync(".env.local","utf8").split("\n").reduce((a,l)=>{const m=l.match(/^([A-Z0-9_]+)=(.*)$/);if(m)a[m[1]]=m[2].replace(/^"|"$/g,"");return a;},{});
const sb = createClient(env.SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY, { auth:{persistSession:false}});
const { data: bizs } = await sb.from("businesses").select("id,name,timezone").ilike("name","%KLIK FOTO%");
console.log("BIZ:", JSON.stringify(bizs));
const biz = bizs.find(b=>/DEV/i.test(b.name)) ?? bizs[0];
console.log("USING:", biz.name, biz.id);
const { data: exp } = await sb.from("expenses").select("id,category,amount,expense_date,outlet_id,note").eq("business_id", biz.id).order("expense_date",{ascending:false});
console.log("EXPENSES count:", exp?.length);
console.log(JSON.stringify(exp,null,1));
const cats = {};
for (const e of exp??[]) cats[e.category]=(cats[e.category]??0)+e.amount;
console.log("BY CATEGORY:", JSON.stringify(cats));
const { data: outs } = await sb.from("outlets").select("id,name").eq("business_id", biz.id);
console.log("OUTLETS:", JSON.stringify(outs));
const fromIso = new Date(Date.now()-29*86400000).toISOString();
const toIso = new Date().toISOString();
const { data: tx } = await sb.rpc("dashboard_tx_summary",{p_business:biz.id,p_start:fromIso,p_end:toIso});
console.log("TX SUMMARY(30d):", JSON.stringify(tx));
const { data: exsum } = await sb.rpc("finance_expense_summary",{p_business:biz.id,p_from:new Date(Date.now()-29*86400000).toISOString().slice(0,10),p_to:new Date().toISOString().slice(0,10)});
console.log("EXPENSE SUMMARY(30d):", JSON.stringify(exsum));
